// Seeds the database with two ready-made survey forms, transcribed from the
// questionnaires provided. Run once with: npm run seed
//
// Known limitation: a few source questions used branching ("skip to
// question N depending on your answer") — this platform doesn't support
// conditional branching yet, so those are included as plain linear
// questions.
import { db } from "./db.js";
import { nanoid } from "nanoid";

function matrix(rows, columns) {
  return { type: "matrix", config: { rows, columns } };
}

// A matrix row the respondent can type their own answer into, instead of
// picking a column — used in place of a plain "Иное" (Other) да/нет row.
function freeTextRow(label) {
  return { label, freeText: true };
}

function choice(options, { other = false, required = false } = {}) {
  return { type: "multiple_choice", options, config: other ? { allowOther: true } : {}, required };
}

function insertForm(title, description, questions) {
  const formId = nanoid(10);
  const now = new Date().toISOString();
  db.prepare(
    "INSERT INTO forms (id, title, description, created_at, updated_at) VALUES (?, ?, ?, ?, ?)"
  ).run(formId, title, description, now, now);

  const insertQ = db.prepare(
    `INSERT INTO questions (id, form_id, type, title, description, required, options, config, position)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)`
  );
  questions.forEach((q, index) => {
    insertQ.run(
      nanoid(10),
      formId,
      q.type || "short_text",
      q.title,
      q.description || "",
      q.required ? 1 : 0,
      JSON.stringify(q.options || []),
      JSON.stringify(q.config || {}),
      index
    );
  });
  return formId;
}

